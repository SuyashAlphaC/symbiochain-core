  async function send(
    operation: string,
    signer: Account,
    receiver: string,
    txActions: Parameters<Account['signAndSendTransaction']>[0]['actions'],
  ) {
    requireTestnetAccount(signer.accountId);
    requireTestnetAccount(receiver);
    await requireTestnetNetwork(() => provider.viewNodeStatus());
    const binding = digest({
      signer: signer.accountId,
      receiver,
      txActions: JSON.parse(
        JSON.stringify(txActions, (_k, v) => (typeof v === 'bigint' ? v.toString() : v)),
      ),
    });
    const prior = state.journal[operation];
    if (prior) {
      assert.equal(prior.binding, binding, 'Rehearsal operation conflicts with persisted terms');
      if (prior.status === 'COMPLETE') return prior.outcome!;
      assert.ok(
        prior.signedBase64,
        'Legacy unknown transaction outcome requires explicit reconciliation',
      );
    }
    const signed = prior?.signedBase64
      ? SignedTransaction.decode(Buffer.from(prior.signedBase64, 'base64'))
      : await signer.createSignedTransaction({ receiverId: receiver, actions: txActions });
    const signedBase64 = Buffer.from(signed.encode()).toString('base64');
    state.journal[operation] = { binding, status: 'STARTED', signedBase64 };
    await save(`${directory}/state.json`, state);
    // Retries only reuse the exact persisted signature/nonce. Never ask the SDK
    // to regenerate a transaction after an unknown submission result.
    const outcome = await provider.sendTransactionUntil(signed, 'FINAL');
    state.journal[operation] = { binding, status: 'COMPLETE', signedBase64, outcome };
    await save(`${directory}/state.json`, state);
    const success = !JSON.stringify(outcome.status).includes('Failure');
    report.transactions.push({ operation, hash: outcome.transaction.hash, receiver, success });
    await publish();
    return outcome;
  }
